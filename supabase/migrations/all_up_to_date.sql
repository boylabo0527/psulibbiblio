create unique index if not exists programs_unique on programs (name);

-- ---------------------------------------------------------------------------
-- 05: campuses + program-campus offerings become database-managed
-- ---------------------------------------------------------------------------
create table if not exists campuses (
  id bigint generated by default as identity primary key,
  name text not null,
  created_at timestamptz default now()
);
create unique index if not exists campuses_name_unique on campuses (name);

create table if not exists program_campuses (
  id bigint generated by default as identity primary key,
  program_id bigint not null references programs(id) on delete cascade,
  campus_id bigint not null references campuses(id) on delete cascade,
  created_at timestamptz default now()
);
create unique index if not exists program_campuses_unique on program_campuses (program_id, campus_id);

