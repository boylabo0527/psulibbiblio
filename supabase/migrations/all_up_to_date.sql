-- ---------------------------------------------------------------------------
-- 08: full-text search index for scalable matching (500k+ row catalogs)
-- NOTE: on a large catalog, run this section's statements SEPARATELY (see
-- supabase/migrations/08_titles_fulltext_search.sql for the split-out,
-- copy-pasteable version) -- combined here only for smaller/fresh databases.
-- ---------------------------------------------------------------------------
set statement_timeout = '15min';

alter table titles add column if not exists search_vector tsvector
  generated always as (
    to_tsvector('english',
      coalesce(title, '') || ' ' ||
      coalesce(author, '') || ' ' ||
      coalesce(publisher, '') || ' ' ||
      coalesce(subjects, '')
    )
  ) stored;

create index if not exists titles_search_idx on titles using gin (search_vector);

create or replace function match_titles_candidates(query_text text, limit_n int)
returns table (
  id bigint,
  format text,
  title text,
  author text,
  publisher text,
  year text,
  subjects text,
  embedding jsonb,
  lexical_rank real
)
language sql stable
as $$
  select sub.id, sub.format, sub.title, sub.author, sub.publisher, sub.year, sub.subjects,
         sub.embedding, ts_rank_cd(sub.search_vector, to_tsquery('english', query_text)) as lexical_rank
  from (
    select t.id, t.format, t.title, t.author, t.publisher, t.year, t.subjects,
           t.embedding, t.search_vector
    from titles t
    where t.search_vector @@ to_tsquery('english', query_text)
    limit greatest(limit_n * 20, 3000)
  ) sub
  order by lexical_rank desc
  limit limit_n;
$$;

